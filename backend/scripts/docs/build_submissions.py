"""
Builds the four individual Assignment 03 submissions from the official template.

    python scripts/docs/build_submissions.py <template.docx>

Inputs (all generated by the project, nothing typed by hand):
  - tools-local/spec.json                     request spec (scripts/postman/spec.js)
  - screenshots/MemberN/*.png + manifest.json Postman desktop screenshots and the status the server logged
  - postman/newman-reports/MemberN.json       response bodies received by Newman (Postman CLI) runs
  - backend/src/**                            code snippets are extracted from the real source files
Output: submissions/MemberN_Assignment03.docx
"""
import copy
import json
import re
import sys
from datetime import date
from pathlib import Path

import docx
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "backend" / "src"
SPEC = json.loads((ROOT / "tools-local" / "spec.json").read_text(encoding="utf-8"))
OUT = ROOT / "submissions"
FONT = "Times New Roman"
MONO = "Consolas"
SUBMISSION_DATE = date(2026, 11, 5).strftime("%d %B %Y")


# ---------------------------------------------------------------- source extraction
def read(rel):
    return (SRC / rel).read_text(encoding="utf-8")


def extract_function(rel, name):
    lines = read(rel).splitlines()
    start = next(i for i, l in enumerate(lines) if re.match(rf"^(async )?function {re.escape(name)}\(", l))
    # include the doc comment directly above, if any
    while start > 0 and lines[start - 1].strip().startswith(("/**", "*", "//")):
        start -= 1
    end = next(i for i in range(start, len(lines)) if lines[i] == "}")
    return "\n".join(lines[start : end + 1])


def route_for(method, path):
    """Finds the router line for METHOD + path, and the controller function it calls."""
    p = path.split("?")[0]
    p = re.sub(r"^/api", "", p)
    segs = []
    for s in p.strip("/").split("/"):
        segs.append(None if (s.startswith("{{") or re.fullmatch(r"[0-9a-f]{24}", s)) else s)
    for f in sorted((SRC / "routes").glob("*.routes.js")):
        text = f.read_text(encoding="utf-8")
        for line in text.splitlines():
            m = re.match(rf"\s*router\.{method.lower()}\('([^']+)'", line)
            if not m:
                continue
            rsegs = m.group(1).strip("/").split("/")
            if len(rsegs) != len(segs):
                continue
            if all((a is None and b.startswith(":")) or a == b for a, b in zip(segs, rsegs)):
                ctrl = re.search(r"ctrl\.(\w+)", line).group(1)
                cfile = re.search(r"require\('\.\./controllers/([\w.]+)'\)", text).group(1) + ".js"
                return f.name, line.strip(), cfile, ctrl
    raise ValueError(f"route not found for {method} {path}")


# ---------------------------------------------------------------- newman responses
def newman_responses(member):
    path = ROOT / "postman" / "newman-reports" / f"Member{member}.json"
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    out = {}
    for ex in data["run"]["executions"]:
        name = ex["item"]["name"]
        rid = name.split(" ")[0]
        resp = ex.get("response") or {}
        body = bytes(resp.get("stream", {}).get("data", [])).decode("utf-8", "replace")
        out[rid] = {"code": resp.get("code"), "status": resp.get("status"), "body": body}
    return out


def pretty_excerpt(body, max_lines=28):
    try:
        text = json.dumps(json.loads(body), indent=2, ensure_ascii=False)
    except Exception:
        text = body
    lines = text.splitlines()
    if len(lines) > max_lines:
        lines = lines[:max_lines] + ["  ... (truncated - full response in the Postman screenshot / collection run)"]
    return "\n".join(lines)


# ---------------------------------------------------------------- docx helpers
def set_cell_bg(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def shade_paragraph(p, hex_color="F3F4F6"):
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    pPr.append(shd)


def run(p, text, bold=False, size=11, font=FONT, color=None, italic=False):
    r = p.add_run(text)
    r.bold = bold
    r.italic = italic
    r.font.size = Pt(size)
    r.font.name = font
    r._element.rPr.rFonts.set(qn("w:eastAsia"), font)
    if color:
        r.font.color.rgb = RGBColor.from_string(color)
    return r


class Builder:
    """Appends content at the end of the body; elements are later moved to their place in the template."""

    def __init__(self, doc):
        self.doc = doc
        self.elements = []

    def _track(self, obj):
        self.elements.append(obj._element if hasattr(obj, "_element") else obj._p)
        return obj

    def para(self, text="", bold=False, size=11, align=None, space_after=4, italic=False, color=None, keep_next=False):
        p = self.doc.add_paragraph()
        if text:
            run(p, text, bold=bold, size=size, italic=italic, color=color)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.space_before = Pt(0)
        if keep_next:
            p.paragraph_format.keep_with_next = True
        if align:
            p.alignment = align
        return self._track(p)

    def heading(self, text, size=14, color="1F3864", page_break=False, underline=False):
        p = self.doc.add_paragraph()
        if page_break:
            p.paragraph_format.page_break_before = True
        r = run(p, text, bold=True, size=size, color=color)
        r.underline = underline
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.keep_with_next = True
        return self._track(p)

    def code(self, text, size=8):
        for i, line in enumerate(text.splitlines() or [""]):
            p = self.doc.add_paragraph()
            run(p, line if line else " ", size=size, font=MONO)
            f = p.paragraph_format
            f.space_after = Pt(0)
            f.space_before = Pt(0)
            f.line_spacing = 1.0
            shade_paragraph(p)
            self._track(p)
        self.para(space_after=2)

    def table(self, rows, widths=(1.6, 4.9), header=None):
        t = self.doc.add_table(rows=0, cols=2)
        t.style = self.doc.styles["Table Grid"] if "Table Grid" in [s.name for s in self.doc.styles] else None
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        if header:
            cells = t.add_row().cells
            for c, txt in zip(cells, header):
                c.paragraphs[0].paragraph_format.space_after = Pt(0)
                run(c.paragraphs[0], txt, bold=True, size=10, color="FFFFFF")
                set_cell_bg(c, "1F3864")
        for k, v in rows:
            cells = t.add_row().cells
            run(cells[0].paragraphs[0], k, bold=True, size=10)
            set_cell_bg(cells[0], "E8EEF7")
            mono = k in ("Endpoint URL", "Headers", "Body / Parameters", "Route")
            parts = v.split("\n")
            for i, part in enumerate(parts):
                p = cells[1].paragraphs[0] if i == 0 else cells[1].add_paragraph()
                p.paragraph_format.space_after = Pt(0)
                run(p, part, size=9 if mono else 10, font=MONO if mono else FONT)
            cells[0].paragraphs[0].paragraph_format.space_after = Pt(0)
        for row in t.rows:
            for c, w in zip(row.cells, widths):
                c.width = Inches(w)
        self._track(t)
        self.para(space_after=4)
        return t

    def image(self, path, width=6.5, caption=None):
        # Crop the full Postman window to the request/response panel (drops the History sidebar) for legibility.
        from PIL import Image
        crop_dir = path.parent / "doc-crops"
        crop_dir.mkdir(exist_ok=True)
        cropped = crop_dir / path.name
        with Image.open(path) as im:
            im.crop((476, 112, min(1860, im.width), min(1040, im.height))).save(cropped)
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(str(cropped), width=Inches(width))
        p.paragraph_format.space_after = Pt(2)
        self._track(p)
        if caption:
            self.para(caption, size=9, italic=True, align=WD_ALIGN_PARAGRAPH.CENTER, color="555555", space_after=8)


# ---------------------------------------------------------------- content
def headers_text(r):
    h = []
    if r.get("auth"):
        h.append(f"Authorization: Bearer <JWT of {r['auth'].replace('Token', '')} account>")
    if r.get("body"):
        h.append("Content-Type: application/json")
    if r.get("form"):
        h.append("Content-Type: multipart/form-data (set automatically by Postman)")
    return "\n".join(h) if h else "None"


def body_text(r):
    parts = []
    if r.get("query"):
        parts.append("Query parameters:")
        parts += [f"  {k} = {v}" for k, v in r["query"].items()]
    if r.get("body") is not None:
        parts.append("JSON body:")
        parts += json.dumps(r["body"], indent=2).splitlines()
    if r.get("form"):
        parts.append("form-data:")
        for f in r["form"]:
            parts.append(f"  {f['key']} = (file) {Path(f['file']).name}" if f.get("file") else f"  {f['key']} = {f['value']}")
    path_params = re.findall(r"\{\{(\w+)\}\}", r["path"])
    if path_params:
        parts.append("Path parameters: " + ", ".join(path_params) + " (id returned by an earlier request)")
    return "\n".join(parts) if parts else "None"


def auth_text(r):
    roles = {"ownerToken": "Pharmacy owner", "owner2Token": "Pharmacy owner (another pharmacy)", "newOwnerToken": "Pharmacy owner (no pharmacy yet)",
             "rejectedOwnerToken": "Pharmacy owner (rejected pharmacy)", "patientToken": "Patient", "patient2Token": "Patient", "adminToken": "Admin"}
    if not r.get("auth"):
        return "Public (no login required)"
    return f"JWT required - role: {roles[r['auth']]}"


def curl_example(r, port):
    qs = ""
    if r.get("query"):
        qs = "?" + "&".join(f"{k}={v}" for k, v in r["query"].items())
    url_path = re.sub(r"\{\{(\w+)\}\}", r"<\1>", r["path"])
    lines = [f"curl -X {r['method']} \"http://127.0.0.1:{port}{url_path}{qs}\""]
    if r.get("auth"):
        lines.append(f"  -H \"Authorization: Bearer <{r['auth']}>\"")
    if r.get("body") is not None:
        lines.append("  -H \"Content-Type: application/json\"")
        lines.append(f"  -d '{json.dumps(r['body'])}'")
    for f in r.get("form") or []:
        lines.append(f"  -F \"{f['key']}=@{Path(f['file']).name}\"" if f.get("file") else f"  -F \"{f['key']}={f['value']}\"")
    return " \\\n".join(lines)


def disp(path):
    """Postman variables {{x}} are shown as :x path parameters in the document."""
    return re.sub(r"\{\{(\w+)\}\}", r":\1", path)


STATUS_TEXT = {200: "200 OK", 201: "201 Created", 400: "400 Bad Request", 401: "401 Unauthorized", 403: "403 Forbidden", 404: "404 Not Found", 409: "409 Conflict"}


def build_member(template, member):
    m = SPEC["MEMBERS"][str(member)]
    reqs = {r["id"]: r for r in SPEC["REQUESTS"] if r["member"] == member}
    order = SPEC["ORDER"][str(member)]
    manifest = json.loads((ROOT / "screenshots" / f"Member{member}" / "manifest.json").read_text(encoding="utf-8"))
    responses = newman_responses(member)
    doc = docx.Document(template)
    P = doc.paragraphs

    # ---- cover page
    P[10].runs[1].text = "MedFind BD"
    P[11].runs[1].text = " 02"
    run(P[12], "Node.js + Express.js (MongoDB Atlas, Mongoose)", size=18)
    P[14].runs[1].text = f" : {m['name']}"
    P[15].runs[1].text = f" {m['studentId']}"
    P[16].runs[1].text = "03"
    run(P[20], f" {SUBMISSION_DATE}", size=18, bold=False)

    feat1_heading, feat2_heading = P[26], P[32]
    feat1_heading.paragraph_format.page_break_before = True
    feat2_heading.paragraph_format.page_break_before = True
    # remove the instruction / example block and the empty spacer paragraphs between sections
    for i in list(range(21, 26)) + list(range(27, 32)) + list(range(33, len(P))):
        el = P[i]._p
        el.getparent().remove(el)
    feat1_heading.runs[0].text = f"APIs of Feature - 01: {m['features'][0]}"
    feat2_heading.runs[0].text = f"APIs of Feature - 02: {m['features'][1]}"

    missing = []

    def feature_content(fnum):
        b = Builder(doc)
        items = [reqs[i] for i in order if reqs[i]["feature"] == fnum]
        mains = [r for r in items if r["doc"] == "main"]
        negs = [r for r in items if r["doc"] == "negative"]
        b.para(f"Server: Member {member} backend, started with \"npm run start:member{member}\" on port {m['port']} "
               f"(last four digits of student ID {m['studentId']}). Base URL: http://127.0.0.1:{m['port']}. "
               f"Database: MongoDB (Mongoose ODM), connected at server start.", size=10.5, italic=True, space_after=8)
        summary = [(f"{i + 1}. {r['method']}", f"{disp(r['path'])}  -  {r['name']}") for i, r in enumerate(mains)]
        b.table(summary, widths=(1.1, 5.4), header=("Method", "Endpoint  -  API"))

        for n, r in enumerate(mains, 1):
            b.heading(f"API {n}: {r['name']}", size=13, page_break=n > 1)
            route_file, route_line, cfile, cname = route_for(r["method"], r["path"])
            shot = manifest.get(r["id"])
            if not shot or not shot.get("ok"):
                missing.append(r["id"])
            actual = shot.get("serverLogged") if shot else None
            rows = [
                ("Purpose", r["purpose"]),
                ("Endpoint URL", f"http://127.0.0.1:{m['port']}{disp(r['path'])}"),
                ("HTTP Method", r["method"]),
                ("Headers", headers_text(r)),
                ("Authentication", auth_text(r)),
                ("Body / Parameters", body_text(r)),
                ("Status code", f"Expected {STATUS_TEXT[r['expect']]}; returned {STATUS_TEXT.get(actual, actual)} in the Postman test below"),
            ]
            b.table(rows)
            b.para("Example request (cURL):", bold=True, size=10.5, keep_next=True)
            b.code(curl_example(r, m["port"]))
            resp = responses.get(r["id"])
            if resp:
                b.para(f"Example response ({resp['code']} {resp['status']}, recorded from the Postman collection run):", bold=True, size=10.5, keep_next=True)
                b.code(pretty_excerpt(resp["body"]))
            b.para("Code snippet (route -> controller -> service):", bold=True, size=10.5, keep_next=True)
            snippet = [f"// src/routes/{route_file}", route_line, "", f"// src/controllers/{cfile}", extract_function(f"controllers/{cfile}", cname)]
            for ref in r.get("code", []):
                f, fn = ref.split("#")
                snippet += ["", f"// src/services/{f}", extract_function(f"services/{f}", fn)]
            b.code("\n".join(snippet))
            b.para("Postman screenshot:", bold=True, size=10.5, keep_next=True)
            if shot and (ROOT / shot["screenshot"]).exists():
                b.image(ROOT / shot["screenshot"], caption=f"Figure: {r['id']} - {r['method']} {disp(r['path'])} tested in Postman (status {actual})")

        if negs:
            b.heading(f"Validation and error-handling tests (Feature {fnum:02d})", size=13, page_break=True)
            b.para("The same APIs were also tested with invalid input, wrong roles and invalid state changes. "
                   "Each request below was sent from Postman to the running server.", size=10.5, space_after=6)
            for r in negs:
                shot = manifest.get(r["id"])
                if not shot or not shot.get("ok"):
                    missing.append(r["id"])
                b.para(f"{r['name']}", bold=True, size=11.5, keep_next=True, color="1F3864")
                b.table([
                    ("Request", f"{r['method']} http://127.0.0.1:{m['port']}{disp(r['path'])}"),
                    ("Scenario", r["purpose"]),
                    ("Body / Parameters", body_text(r)),
                    ("Result", f"Expected {STATUS_TEXT[r['expect']]}; returned {STATUS_TEXT.get(shot['serverLogged'], shot['serverLogged']) if shot else 'n/a'}"),
                ])
                if shot and (ROOT / shot["screenshot"]).exists():
                    b.image(ROOT / shot["screenshot"], width=6.0, caption=f"Figure: {r['id']} - {r['name']}")
        return b.elements

    def move_after(anchor_el, elements):
        cur = anchor_el
        for el in elements:
            cur.addnext(el)
            cur = el

    f1 = feature_content(1)
    move_after(feat1_heading._p, f1)
    f2 = feature_content(2)
    move_after(feat2_heading._p, f2)

    # ---- additional implementation notes at the end
    b = Builder(doc)
    b.heading("Implementation Notes", size=14, page_break=True, underline=True)
    b.table([
        ("Project", "MedFind BD - medicine availability and reservation platform (CSE471, Group 02, Section 03)"),
        ("Tech stack", "Node.js, Express.js 5, MongoDB (MongoDB Atlas in deployment, local replica set in development), Mongoose 8, JWT + bcrypt, Multer + Cloudinary (local-disk fallback), node-cron, zod validation"),
        ("My server", f"cd backend\nnpm install\nnpm run seed\nnpm run start:member{member}\n-> http://127.0.0.1:{m['port']}/api/health"),
        ("Environment", "backend/.env (copy of .env.example): MONGODB_URI, JWT_SECRET, PORT_MEMBER1..4, CLOUDINARY_*, SENDGRID_API_KEY, business-rule settings"),
        ("Postman", f"Import postman/Member{member}/Member{member}_{m['studentId']}.postman_collection.json, run the \"00 Setup\" login requests (if present), then run each feature folder top to bottom. File fields use postman/assets/*."),
        ("Architecture", "routes (URL + middleware) -> controllers (HTTP in/out) -> services (business logic) -> Mongoose models. Central error handler returns { success, message, errors }."),
    ])
    b.para("Database connection (src/config/db.js):", bold=True, size=10.5, keep_next=True)
    b.code(read("config/db.js"))
    doc_body = doc.element.body
    sectPr = doc_body.find(qn("w:sectPr"))
    for el in b.elements:
        sectPr.addprevious(el)

    OUT.mkdir(exist_ok=True)
    out = OUT / f"Member{member}_Assignment03.docx"
    doc.save(out)
    return out, missing


if __name__ == "__main__":
    template = sys.argv[1]
    members = [int(a) for a in sys.argv[2:]] or [1, 2, 3, 4]
    for mem in members:
        path, missing = build_member(template, mem)
        print(f"wrote {path.relative_to(ROOT)}" + (f"  MISSING/UNVERIFIED: {missing}" if missing else "  (all screenshots verified)"))
